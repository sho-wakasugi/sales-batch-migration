"""現新比較用の境界ケースCSVを作る（制御文字・CRLF を確実に入れるためスクリプトで生成）。"""
import sys

NBSP = " "
IDSP = "　"  # 全角スペース

lines = [
    ("売上日,店舗コード,商品コード,数量,単価", "\n"),
    ("2026-01-05,S001,P001,1,100", "\n"),                     # 正常
    ("", "\n"),                                                # 空行
    ("   ", "\n"),                                             # 空白だけの行
    (",,,,", "\n"),                                            # 全項目空
    ("2026-01-05,S001,P001,1,100,", "\n"),                    # 末尾カンマ（6項目）
    ("2026-01-05,S001,P001,1,100,X", "\n"),                   # 6項目
    ("2026-01-06,\tS001\t,P001,2,100", "\n"),                 # タブで囲む（trim対象）
    (f"2026-01-07,{IDSP}S001{IDSP},P001,3,100", "\n"),        # 全角スペースで囲む
    (f"2026-01-08,{NBSP}S001{NBSP},P001,4,100", "\n"),        # NBSPで囲む
    (f"2026-01-09,S001,P001,{NBSP},100", "\n"),               # 数量がNBSPのみ
    (f"2026-01-09,S001,P001,{IDSP},100", "\n"),               # 数量が全角スペースのみ
    ("2026-01-10,S001,P001,１,100", "\n"),                    # 全角数字
    ("2026-01-10,S001,P001,+1,100", "\n"),                    # +付き
    ("2026-01-10,S001,P001,01,100", "\n"),                    # 先頭ゼロ（正常）
    ("2026-01-10,S001,P001,1,-0", "\n"),                      # -0（正常）
    ("2026-01-10,S999,P001,9223372036854775807,1", "\n"),     # long最大（正常、単独の店舗にして集計あふれを避ける）
    ("2026-01-10,S001,P001,9223372036854775808,1", "\n"),     # long超え
    ("2026-01-10,S001,P001,4611686018427387904,2", "\n"),     # 掛け算でlong超え
    ("2026-01-10,S001,P001,1,1e3", "\n"),                     # 指数表記
    ("2024-02-29,S001,P001,1,100", "\n"),                     # うるう日（正常）
    ("2026-02-29,S001,P001,1,100", "\n"),                     # 非うるう年
    ("2026-1-5,S001,P001,1,100", "\n"),                       # ゼロ埋め無し
    ("0000-01-01,S001,P001,1,100", "\n"),                     # 0年
    ("9999-12-31,S001,P001,1,100", "\n"),                     # 9999年
    ("２０２６-01-05,S001,P001,1,100", "\n"),                   # 全角数字の日付
    ("2026-01-11,S001,\"P,001\",1,100", "\n"),                # クォート内カンマ
    ("2026-01-11,S001,\"P\"\"001\",1,100", "\n"),             # クォート内のクォート
    ("2026-01-11,S001,P\"001,0,100", "\n"),                   # クォートが途中にある（エラー行で出力確認）
    ("2026-01-11,S001, \"P001\" ,0,100", "\n"),               # クォートの外に空白
    ("2026-01-11,S001,\"P001,0,100", "\n"),                   # 閉じていないクォート
    ("2026-01-12,S001,P001,1,100", "\r\n"),                   # CRLF
    ("2026-01-12,S001,\"\",1,100", "\n"),                     # 空のクォート
    ("2026-01-13,s001,P001,1,100", "\n"),                     # 小文字（並び順）
    ("2026-01-13,東京,P001,1,100", "\n"),                     # 日本語（並び順）
    ("2026-01-13,S\U0001F600,P001,1,100", "\n"),              # 絵文字（UTF-16とUTF-8で順序が逆転）
    ("2026-01-13,Sｱ,P001,1,100", "\n"),                  # 半角カナ
    ("2026-01-14,S001,P\udcff1,0,100", "\n"),                 # 不正なUTF-8バイト（0xFF）
    ("2026-01-14,S002,P001,1,0", ""),                         # 最終行に改行なし
]

with open(sys.argv[1], "w", encoding="utf-8", errors="surrogateescape", newline="") as f:
    for text, eol in lines:
        f.write(text + eol)
print(len(lines) - 1, "data lines")
